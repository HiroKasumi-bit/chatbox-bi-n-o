"""AURA's voice for the game, English and Vietnamese: python3 game/gen_voice.py  (needs edge-tts, ffmpeg and network)
Same treatment as the presentation's AURA: en-GB-SoniaNeural slowed 10%, lowered 6 Hz, light echo, loudness -14 LUFS.
Writes game/voice/<key>_<lang>.mp3 and game/voice.js (text -> file and duration)."""
import json, asyncio, subprocess, os, sys
try:
    import certifi; certifi.where = lambda: os.environ.get('SSL_CERT_FILE', '/root/.ccr/ca-bundle.crt')
except ImportError: pass
import edge_tts
D = os.path.dirname(os.path.abspath(__file__)); V = os.path.join(D, 'voice')
lines = json.loads(subprocess.run(['node', '--input-type=module', '-e', """
import { MISSIONS, FINALE, UI } from '%s/missions.js';
const out = [];
MISSIONS.forEach((m) => { out.push([m.id + '_intro', m.intro]); out.push([m.id + '_done', m.done]); });
out.push(['finale_intro', FINALE.intro], ['finale_win', FINALE.win], ['finale_late', FINALE.late], ['allcards', UI.allCards], ['inside', UI.welcomeInside]);
console.log(JSON.stringify(out));""" % D], capture_output=True, text=True, check=True).stdout)
VOICES = {'en': ('en-GB-SoniaNeural', '-10%', '-6Hz'), 'vi': ('vi-VN-HoaiMyNeural', '-4%', '-4Hz')}
async def tts(text, lang, path):
    v, rate, pitch = VOICES[lang]
    await edge_tts.Communicate(text, v, rate=rate, pitch=pitch).save(path)
manifest = {}
for key, t in lines:
    entry = {}
    for lang in ('en', 'vi'):
        raw = os.path.join(V, f'_raw_{key}_{lang}.mp3'); out = os.path.join(V, f'{key}_{lang}.mp3')
        if not os.path.exists(out) or '--force' in sys.argv:
            asyncio.run(tts(t[lang], lang, raw))
            subprocess.run(['ffmpeg', '-y', '-v', 'error', '-i', raw, '-af', 'highpass=f=180,lowpass=f=7000,aecho=0.8:0.85:7|14:0.35|0.2,aecho=0.8:0.5:120:0.15,apad=pad_dur=0.25,loudnorm=I=-14:TP=-1:LRA=7', '-ar', '44100', '-ac', '1', '-b:a', '64k', out], check=True)
            os.remove(raw)
        dur = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', out], capture_output=True, text=True).stdout)
        entry[lang] = {'src': f'game/voice/{key}_{lang}.mp3', 'dur': round(dur, 2)}
    manifest[t['en']] = entry; print(key, entry['en']['dur'], entry['vi']['dur'], flush=True)
open(os.path.join(D, 'voice.js'), 'w').write('// generated by gen_voice.py: AURA line (English text) -> voice files\nexport const VOICE = ' + json.dumps(manifest, ensure_ascii=False, indent=1) + ';\n')
